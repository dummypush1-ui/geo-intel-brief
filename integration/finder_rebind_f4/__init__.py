"""Explicit-edition consumer artifact preparation. Not runtime rebinding.
Supplied exact generated bytes -> matching catalogue/index/proof in memory.
No auto repins, source changes, credential/provider/publication or activation.
"""
import hashlib,json,re,struct,collections
from pathlib import Path
from integration.code_news_catalogue import extract,model_rows,omission_ledger
from scripts.build_finder_identity_proof import decode_payload,source_systems,offline_identities,derive_records,FRAGMENT,LOOKUP,UNKNOWN
from integration.finder_identity_proof_prep import RECORD
ROOT=Path(__file__).resolve().parents[2]
FLAG='MERGED_FINDER_REBIND_PREP_ENABLED'
MAX_TOTAL=100*1024*1024
class Held(ValueError):pass

def enabled(env):
 if type(env)is not dict or any(type(k)is not str or type(v)is not str for k,v in env.items()):raise Held('Plain environment strings required')
 value=env.get(FLAG,'false')
 if value not in ('true','false'):raise Held('Exact consumer preparation flag required')
 return value=='true'
def sha(raw):return hashlib.sha256(raw).hexdigest()

def source_check(root,pins):
 if type(pins)is not dict or any(type(n)is not str for n in pins)or not {'index.html','offline.html','sw.js'}<set(pins)or len(pins)!=4:raise Held('Exact generated source pins required')
 data=[n for n in pins if re.fullmatch('data\.[a-f0-9]{12}\.js',n)]
 if len(data)!=1:raise Held('One exact data bundle required')
 total=0
 for name,pin in pins.items():
  if type(pin)is not str or not re.fullmatch('[a-f0-9]{64}',pin):raise Held('Full source SHA256 required')
  p=root/name
  if p.is_symlink()or not p.is_file():raise Held('Regular generated source required')
  size=p.stat().st_size;total+=size
  if size>40*1024*1024 or total>MAX_TOTAL:raise Held('Generated source byte cap')
  if sha(p.read_bytes())!=pin:raise Held('Generated source pin mismatch')
 if data[0][5:17]!=pins[data[0]][:12]:raise Held('Bundle filename identity mismatch')
 return data[0]

def prepare(env,*,root=ROOT,pins=None):
 if not enabled(env):return None
 root=Path(root);data_name=source_check(root,pins);edition='snapshot:'+pins[data_name][:12];editions={'HS':'2022','IN':edition}
 try:
  shell=(root/'index.html').read_text();offline=(root/'offline.html').read_text();data=(root/data_name).read_text();sw=(root/'sw.js').read_text()
  if "data.src = './"+data_name+"'"not in shell or data_name not in sw or 'hsn-data-'+pins[data_name][:12]not in sw or data not in offline:raise Held('Generated source identity mismatch')
  tags=source_systems(shell)
  if tags!=source_systems(offline)or len({x[0]for x in tags})!=22:raise Held('Candidate system labels mismatch')
  for text in (shell,offline):
   if any(text.count(seam)!=1 for seam in (FRAGMENT,LOOKUP,UNKNOWN)):raise Held('Candidate identity handler drift')
  rawrows,_=decode_payload(offline);bundlerows,_=decode_payload(data)
  def row_digest(rows):
   h=hashlib.sha256()
   for row in rows:h.update(json.dumps(row,ensure_ascii=True,separators=(',',':')).encode()+b'\n')
   return h.hexdigest()
  if len(rawrows)!=len(bundlerows)or row_digest(rawrows)!=row_digest(bundlerows):raise Held('Candidate offline/data diagnostic mismatch')
  snapshot=extract(root,expected_shell_sha256=pins['index.html'],expected_bundle_sha256=pins[data_name])
  resolved=[dict(r,state='resolved')for r in model_rows(snapshot)];omitted=omission_ledger(snapshot);indexed=resolved+omitted
  groups=collections.defaultdict(list)
  for row in indexed:groups[row['code']].append(row)
  idx=[];payloads=[];offset=0;record=struct.Struct('>12sQI')
  for code in sorted(groups):
   payload=json.dumps(sorted(groups[code],key=lambda r:(r['system'],r['edition'])),ensure_ascii=True,separators=(',',':')).encode()+b'\n'
   if len(payload)>65536 or len(groups[code])>100:raise Held('Candidate index group cap')
   idx.append(record.pack(code.encode().ljust(12,b' '),offset,len(payload)));payloads.append(payload);offset+=len(payload)
  index_bytes=b''.join(idx);rows_bytes=b''.join(payloads)
  proof,reasons=derive_records(offline_identities(rawrows,tags,editions),indexed,editions)
  if not proof or len(proof)>2000000 or len(proof)%RECORD.size:raise Held('Candidate identity proof cap')
  # Completeness is computed from exact multiplicities/descriptions, never from
  # raw-list equality or unchanged catalogue source filenames.
  artifacts={'integration/code_news_index/codes.idx':index_bytes,'integration/code_news_index/rows.jsonl':rows_bytes,'integration/finder_identity_proof.bin':proof}
  manifest={'format':'code_news_flat_v1','source_pins':{'expected_shell_sha256':pins['index.html'],'expected_bundle_sha256':pins[data_name]},'code_count':len(groups),'identity_count':len(indexed),'scope':'preserved_snapshot_not_current_official_verification','files':{n.rsplit('/',1)[1]:{'bytes':len(raw),'sha256':sha(raw)}for n,raw in artifacts.items()if n.startswith('integration/code_news_index/')}}
  artifacts['integration/code_news_index/manifest.json']=(json.dumps(manifest,indent=2)+'\n').encode()
  report={'state':'held_consumer_artifacts_not_rebound','source_pins':dict(pins),'editions':editions,'raw_rows':len(rawrows),'raw_list_equal_diagnostic_only':True,'bound_count':len(proof)//RECORD.size,'not_bound_reasons':reasons,'code_count':len(groups),'identity_count':len(indexed),'artifacts':{n:{'bytes':len(raw),'sha256':sha(raw)}for n,raw in artifacts.items()},'runtime_rebinding':'not_applied','public_safety_rewrites':'not_yet_rendered_against_candidate','source_labels_verified':False,'writes':False,'published':False,'auto_repin':False,'provider_calls':0}
  return report,artifacts
 except Held:raise
 except Exception:raise Held('Candidate artifact preparation unavailable; last-good unchanged')from None
